#!/usr/bin/env node
/* Builds js/radar.js: a reading list of fresh headlines from the feeds in content/feed-sources.json.
   Only the title, link, source and date are kept. Each link opens the original article.
   The deploy workflow runs this every day. If a feed is down it is skipped. Needs Node 18+.
       node tools/fetch-feed.js
*/
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'content/feed-sources.json'), 'utf8'));
const out = path.join(root, 'js/radar.js');

function decode(s) {
  return String(s || '')
    .replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&#(\d+);/g, (m, n) => String.fromCodePoint(+n))
    .replace(/&#x([0-9a-f]+);/gi, (m, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;|&#39;/g, "'")
    .replace(/\s+/g, ' ').trim();
}
function tag(block, name) {
  const m = block.match(new RegExp('<' + name + '(?:\\s[^>]*)?>([\\s\\S]*?)</' + name + '>', 'i'));
  return m ? m[1] : '';
}
function parse(xml) {
  const items = [];
  const re = /<(item|entry)(?:\s[^>]*)?>([\s\S]*?)<\/\1>/gi;
  let m;
  while ((m = re.exec(xml))) {
    const b = m[2];
    let link = decode(tag(b, 'link'));
    if (!link) { const l = b.match(/<link[^>]*href=["']([^"']+)["']/i); link = l ? l[1] : ''; }
    const alt = b.match(/<link[^>]*rel=["']alternate["'][^>]*href=["']([^"']+)["']/i);
    if (alt) link = alt[1];
    const date = new Date(decode(tag(b, 'pubDate') || tag(b, 'published') || tag(b, 'updated') || tag(b, 'dc:date')));
    const title = decode(tag(b, 'title'));
    if (title && /^https?:\/\//.test(link) && !isNaN(date)) items.push({ title, url: link.replace(/\?source=.*$/, ''), date });
  }
  return items;
}
async function get(url) {
  const ctl = new AbortController();
  const t = setTimeout(() => ctl.abort(), 15000);
  try {
    const r = await fetch(url, { signal: ctl.signal, headers: { 'user-agent': 'Mozilla/5.0 (portfolio-radar)', accept: 'application/rss+xml, application/atom+xml, text/xml, */*' } });
    if (!r.ok) throw new Error('HTTP ' + r.status);
    return await r.text();
  } finally { clearTimeout(t); }
}

(async () => {
  const sources = cfg.sources.slice();
  /* your own Medium posts, if profile.json has links.medium like https://medium.com/@name */
  try {
    const prof = JSON.parse(fs.readFileSync(path.join(root, 'content/profile.json'), 'utf8'));
    const med = prof.profile && prof.profile.links && prof.profile.links.medium;
    const h = med && String(med).match(/medium\.com\/(@[\w.-]+)/);
    if (h) sources.unshift({ name: 'My Medium', topic: 'Mine', url: 'https://medium.com/feed/' + h[1], mine: true });
  } catch (e) {}

  const cutoff = Date.now() - (cfg.maxAgeDays || 21) * 864e5;
  const seen = new Set(), all = [], ok = [];
  const res = await Promise.allSettled(sources.map((s) => get(s.url)));
  res.forEach((r, i) => {
    const s = sources[i];
    if (r.status !== 'fulfilled') { console.log('skip', s.name, '-', r.reason && r.reason.message); return; }
    const items = parse(r.value).filter((x) => x.date.getTime() >= cutoff && x.date.getTime() <= Date.now() + 864e5)
      .sort((a, b) => b.date - a.date).slice(0, cfg.maxPerSource || 8);
    if (items.length) ok.push(s.name);
    items.forEach((x) => { if (seen.has(x.url)) return; seen.add(x.url); all.push({ t: x.title, u: x.url, s: s.name, k: s.topic || 'Tech', d: x.date.toISOString(), m: s.mine ? 1 : 0 }); });
  });
  all.sort((a, b) => (b.d > a.d ? 1 : -1));
  const list = all.slice(0, cfg.maxTotal || 60);

  /* if every feed failed, keep the last good file instead of wiping the list */
  if (!list.length && fs.existsSync(out)) { console.log('no items fetched; keeping existing js/radar.js'); return; }
  const data = { updated: new Date().toISOString(), sources: ok, items: list };
  fs.writeFileSync(out, '/* generated by tools/fetch-feed.js. Do not edit. */\nwindow.RADAR = ' + JSON.stringify(data) + ';\n');
  console.log('radar:', list.length, 'items from', ok.length, 'of', sources.length, 'feeds');
})();
