#!/usr/bin/env node
/* Turns your content files into the two scripts the website loads.

     content/profile.json    name, email, links, colours
     content/sections.json   the scroll stations (each picks a 3D scene)
     content/lists.json      services, projects, testimonials, timeline, skills, sphere
     content/posts/*.md      blog posts (Markdown with a small header)

   writes   js/content.js  and  js/posts.js

   You can edit the content files by hand, or use the dashboard at /admin (see docs/DASHBOARD.md).
   The GitHub workflow runs this on every deploy. To run it yourself:   npm install js-yaml   then   node tools/build-data.js
*/
const fs = require('fs');
const path = require('path');
let yaml;
try { yaml = require('js-yaml'); } catch (e) { console.error('Run  npm install js-yaml  first.'); process.exit(1); }

const root = path.resolve(__dirname, '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, 'content', f), 'utf8'));
const SCENES = ['phone', 'headset', 'sync', 'chain', 'agentapp', 'globe', 'apps', 'book', 'helix', 'sphere', 'toolbox', 'knot', 'feed'];

const prof = read('profile.json');
const secs = read('sections.json').sections;
const lists = read('lists.json');

const warn = (m) => console.warn('warning:', m);
const seen = new Set();
const sections = secs.map((s, i) => {
  const c = Object.assign({}, s);
  if (!c.id) warn('section ' + (i + 1) + ' has no id');
  else if (seen.has(c.id)) warn('duplicate section id "' + c.id + '"'); else seen.add(c.id);
  if (c.scene && SCENES.indexOf(c.scene) < 0) warn('section "' + c.id + '" uses unknown scene "' + c.scene + '"');
  if (typeof c.sceneOptions === 'string') {
    if (c.sceneOptions.trim()) { try { c.sceneOptions = JSON.parse(c.sceneOptions); } catch (e) { warn('sceneOptions of "' + c.id + '" is not valid JSON, ignored'); delete c.sceneOptions; } }
    else delete c.sceneOptions;
  }
  Object.keys(c).forEach((k) => { if (c[k] === '' || c[k] == null || (Array.isArray(c[k]) && !c[k].length)) delete c[k]; });
  return c;
});

const data = Object.assign({ theme: prof.theme, profile: prof.profile, sections }, lists);
fs.writeFileSync(path.join(root, 'js', 'content.js'),
  '/* GENERATED by tools/build-data.js from the files in content/. Edit those (or use /admin), not this file. */\nwindow.PORTFOLIO = ' + JSON.stringify(data, null, 2) + ';\n');

const dir = path.join(root, 'content', 'posts');
const posts = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.md')).map((f) => {
  const raw = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r/g, '');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) { warn(f + ' has no header, skipped'); return null; }
  const h = yaml.load(m[1]) || {};
  const d = h.date instanceof Date ? h.date.toISOString().slice(0, 10) : String(h.date || '').slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(d)) warn(f + ' needs a date like 2026-10-31');
  return {
    slug: String(h.slug || f.replace(/\.md$/, '')).toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, ''),
    date: d, title: String(h.title || f), summary: h.summary ? String(h.summary) : '',
    tags: Array.isArray(h.tags) ? h.tags.map(String) : [], draft: !!h.draft, body: m[2].trim() + '\n'
  };
}).filter(Boolean) : [];
fs.writeFileSync(path.join(root, 'js', 'posts.js'),
  '/* GENERATED by tools/build-data.js from content/posts/*.md. Edit those (or use /admin), not this file. */\nwindow.POSTS = ' + JSON.stringify(posts, null, 2) + ';\n');
console.log('built js/content.js (' + sections.length + ' sections) and js/posts.js (' + posts.length + ' post' + (posts.length === 1 ? '' : 's') + ')');
